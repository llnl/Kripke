"""CI package used to generate Kripke host-config files.

The upstream Spack package builds Kripke directly and has no hostconfig phase.
Kripke CI builds the checked-out source separately, so this package preserves
that workflow while obtaining dependencies from the shared Spack environment.
"""

import os
import socket

from spack_repo.builtin.build_systems.cmake import CMakePackage
from spack_repo.builtin.build_systems.cuda import CudaPackage
from spack_repo.builtin.build_systems.rocm import ROCmPackage
from spack.package import *


class Kripke(CMakePackage, CudaPackage, ROCmPackage):
    homepage = "https://github.com/LLNL/Kripke"
    git = "https://github.com/LLNL/Kripke.git"

    version("develop", branch="develop", submodules=True)

    variant("mpi", default=True, description="Build with MPI")
    variant("openmp", default=False, description="Build with OpenMP")
    variant("caliper", default=False, description="Build with Caliper")
    variant("raja", default=True, description="Build with RAJA, CHAI, and Umpire")

    depends_on("c", type="build")
    depends_on("cxx", type="build")
    depends_on("cmake@3.23:", type="build")
    depends_on("blt", type="build")
    depends_on("mpi", when="+mpi")
    depends_on("camp", when="+raja")
    depends_on("raja", when="+raja")
    depends_on("chai+raja", when="+raja")
    depends_on("umpire", when="+raja")
    depends_on("caliper", when="+caliper")
    depends_on("adiak@0.4:", when="+caliper")

    phases = ["hostconfig", "cmake", "build", "install"]

    def _hostconfig_path(self, spec):
        hostname = socket.gethostname().rstrip("1234567890")
        sys_type = os.environ.get("SYS_TYPE", str(spec.architecture))
        return os.path.join(
            self.stage.source_path,
            "hc-{0}-{1}-{2}-{3}.cmake".format(hostname, sys_type, spec.compiler, spec.dag_hash()),
        )

    @staticmethod
    def _cache_entry(name, value, value_type="PATH"):
        return 'set({0} "{1}" CACHE {2} "" FORCE)\n'.format(name, value, value_type)

    @staticmethod
    def _cache_option(name, enabled):
        return 'set({0} {1} CACHE BOOL "" FORCE)\n'.format(name, "ON" if enabled else "OFF")

    def hostconfig(self, spec, prefix):
        path = self._hostconfig_path(spec)
        c_compiler = os.environ["SPACK_CC"]
        cxx_compiler = os.environ["SPACK_CXX"]

        with open(path, "w", encoding="utf-8") as config:
            config.write("# Generated by the Kripke CI Spack package.\n")
            config.write(self._cache_entry("CMAKE_C_COMPILER", c_compiler))
            config.write(self._cache_entry("CMAKE_CXX_COMPILER", cxx_compiler))
            config.write(self._cache_entry("CMAKE_BUILD_TYPE", "Release", "STRING"))
            config.write(self._cache_entry("BLT_SOURCE_DIR", spec["blt"].prefix))
            config.write(self._cache_option("ENABLE_MPI", "+mpi" in spec))
            config.write(self._cache_option("ENABLE_MPI_WRAPPER", "+mpi" in spec))
            config.write(self._cache_option("ENABLE_OPENMP", "+openmp" in spec))
            config.write(self._cache_option("ENABLE_CALIPER", "+caliper" in spec))
            config.write(self._cache_option("ENABLE_TESTS", True))
            config.write(self._cache_option("ENABLE_CHAI", "+raja" in spec))

            if "+raja" in spec:
                config.write(self._cache_entry("CAMP_DIR", spec["camp"].prefix))
                config.write(self._cache_entry("RAJA_DIR", spec["raja"].prefix))
                config.write(self._cache_entry("chai_DIR", spec["chai"].prefix))
                config.write(self._cache_entry("umpire_DIR", spec["umpire"].prefix))

            if "+cuda" in spec:
                config.write(self._cache_option("ENABLE_CUDA", True))
                config.write(self._cache_entry("CUDA_TOOLKIT_ROOT_DIR", spec["cuda"].prefix))
                config.write(self._cache_entry("CMAKE_CUDA_HOST_COMPILER", cxx_compiler))
                if not spec.satisfies("cuda_arch=none"):
                    config.write(self._cache_entry("CMAKE_CUDA_ARCHITECTURES", spec.variants["cuda_arch"].value[0], "STRING"))
            else:
                config.write(self._cache_option("ENABLE_CUDA", False))

            if "+rocm" in spec:
                config.write(self._cache_option("ENABLE_HIP", True))
                config.write(self._cache_entry("HIP_ROOT_DIR", spec["hip"].prefix))
                config.write(self._cache_entry("HIP_CLANG_PATH", os.path.join(spec["hip"].prefix, "..", "llvm", "bin")))
                if not spec.satisfies("amdgpu_target=none"):
                    config.write(self._cache_entry("CMAKE_HIP_ARCHITECTURES", ";".join(spec.variants["amdgpu_target"].value), "STRING"))
            else:
                config.write(self._cache_option("ENABLE_HIP", False))

        print("OUT: host-config file {0}".format(path))

    def cmake_args(self):
        return ["-C", self._hostconfig_path(self.spec)]
